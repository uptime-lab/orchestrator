#!/usr/bin/env bash
# Tests for check_proto_copies.sh against a synthetic repository layout.
# Usage: check_proto_copies_test.sh [PATH_TO_SCRIPT_UNDER_TEST]
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
script="${1:-$here/check_proto_copies.sh}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

failures=0
expect() { # expect <label> <expected exit> <command...>
  local label="$1" want="$2"; shift 2
  local got=0
  "$@" >"$tmp/out" 2>&1 || got=$?
  if [ "$got" -ne "$want" ]; then
    echo "FAIL $label: exit $got, wanted $want"; sed 's/^/    /' "$tmp/out"; failures=$((failures + 1))
  else
    echo "ok   $label"
  fi
}

make_layout() { # make_layout <root>
  local r="$1"
  mkdir -p "$r/proto" "$r/agent/pkg/grpc/proto" "$r/backend/pkg/grpc/proto"
  cat >"$r/proto/Makefile" <<'EOF'
PROTO_FILE = x.proto
GENERATED_FILES = x.pb.go x_grpc.pb.go
AGENT_DIR = ../agent
BACKEND_DIR = ../backend
AGENT_PROTO_DIR = $(AGENT_DIR)/pkg/grpc/proto
BACKEND_PROTO_DIR = $(BACKEND_DIR)/pkg/grpc/proto
EOF
  for d in proto agent/pkg/grpc/proto backend/pkg/grpc/proto; do
    printf '// Code generated by protoc-gen-go. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-go v1.2.3\n// \tprotoc        v4.5.6\npackage x\n' >"$r/$d/x.pb.go"
    printf '// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n// versions:\n// - protoc-gen-go-grpc v1.0.0\n// - protoc             v4.5.6\npackage x\n' >"$r/$d/x_grpc.pb.go"
  done
}

# identical copies pass
make_layout "$tmp/ok"
expect "identical copies" 0 "$script" "$tmp/ok"
grep -q "proto copies: identical" "$tmp/out" || { echo "FAIL identical copies: verdict line missing"; failures=$((failures + 1)); }
grep -q "not pinned" "$tmp/out" || { echo "FAIL identical copies: unpinned note missing"; failures=$((failures + 1)); }

# a byte differs in one copy
make_layout "$tmp/diff"
printf '// extra\n' >>"$tmp/diff/backend/pkg/grpc/proto/x.pb.go"
expect "one copy differs" 1 "$script" "$tmp/diff"
grep -q "DIFFERS" "$tmp/out" || { echo "FAIL one copy differs: no DIFFERS line"; failures=$((failures + 1)); }

# a copy is missing
make_layout "$tmp/missing"
rm "$tmp/missing/agent/pkg/grpc/proto/x_grpc.pb.go"
expect "a copy is missing" 1 "$script" "$tmp/missing"
grep -q "MISSING" "$tmp/out" || { echo "FAIL a copy is missing: no MISSING line"; failures=$((failures + 1)); }

# same bytes everywhere but the generator header disagrees with a pin
make_layout "$tmp/pin"
printf 'PROTOC_GEN_GO_VERSION = v9.9.9\n' >>"$tmp/pin/proto/Makefile"
expect "pin mismatch" 1 "$script" "$tmp/pin"
grep -q "PIN MISMATCH" "$tmp/out" || { echo "FAIL pin mismatch: no PIN MISMATCH line"; failures=$((failures + 1)); }

# a matching pin passes
make_layout "$tmp/pinok"
printf 'PROTOC_GEN_GO_VERSION = v1.2.3\nPROTOC_GEN_GO_GRPC_VERSION = v1.0.0\n' >>"$tmp/pinok/proto/Makefile"
expect "pin matches" 0 "$script" "$tmp/pinok"

# no Makefile is a setup error
mkdir -p "$tmp/empty"
expect "no makefile" 2 "$script" "$tmp/empty"

if [ "$failures" -ne 0 ]; then
  echo "FAILED ($failures)"; exit 1
fi
echo "OK"
