#!/usr/bin/env python3
"""Public shape checker: flags identifier SHAPES that do not belong in a public tree.

This checker holds no list of real identifiers and no secret. It recognises
shapes only (a device serial, a private address, a vendor MAC prefix, a home
directory, a mailbox outside the example domains, an internal hostname, the
phrasing of a private engineering journal) and the two file properties that
never belong in a source tree (size, executable magic). Because it sees shapes
and not values, it runs on a fork pull request with no secrets and no network.
An exact-list check that knows the real values exists outside this repository
and is the check that decides a merge; this one is the first line, not the last.

Usage:
  check_public_shape.py --tree DIR            scan every file under DIR
  check_public_shape.py --files PATH...       scan the given files (`-` = stdin list)
  check_public_shape.py --commit REV          scan a commit's added lines and message
  check_public_shape.py --range A..B          every commit in the range
  check_public_shape.py --staged              the index diff (pre-commit hook)
  check_public_shape.py --stdin               text on stdin (commit-msg hook)

Exit status: 0 clean, 1 findings, 2 usage or environment error.
Output: one finding per line, `path:line:rule: message`; `--format github`
emits workflow annotations instead. A documented false positive is silenced on
its own line with the marker `publication-guard: allow <rule>[,<rule>]`; every
opt-out is counted and listed in the summary so that it can be reviewed.

A finding that has no line of its own to carry a marker -- a file rule on a
binary, or a line of a third-party text that must be reproduced unaltered --
is silenced by an entry in `.publication-guard-allow` at the root of the tree
(`--tree` mode only), one `<path> <rule>[,<rule>]  # reason` per line. The
reason is required, every use is an opt-out like a marker, an entry that
silences nothing is a usage error (a stale entry is a hole nobody sees), and
the `gitattributes` rule cannot be silenced at all.
"""

